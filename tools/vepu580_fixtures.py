#!/usr/bin/env python3
"""Writes src/vepu580_fixtures.rs (test-only): the VEPU580 register images the vendor MPP build on AOS programmed,
captured with tools/mppshim.c from `gst-launch-1.0 ... mppjpegdec ! mpph264enc rc-mode=cbr bps=4000000 gop=30 ...`
(see the README), for the first IDR and the first P frame at each captured size, with the per-frame inputs that
image was made from (QP, bit target, slice syntax, dual-core ids). 1280x720 is stored whole; every other size as
the words that differ from 1280x720. Buffer-address registers (dmabuf fds of the capture run) are left out.

usage: tools/vepu580_fixtures.py tools/captures/*.log.gz > src/vepu580_fixtures.rs
"""
import os, sys
from mpplog import parse

CLASSES = [(0x0000, 24), (0x0280, 94), (0x1000, 57), (0x1700, 180), (0x2000, 122), (0x2200, 679)]
FDS = set(range(0x280, 0x2c0, 4))

def image(w):
    return {a: w.get(a, 0) for start, n in CLASSES for a in range(start, start + 4 * n, 4) if a not in FDS}

def inputs(w):
    g = lambda a, lsb, n: (w[a] >> lsb) & ((1 << n) - 1)
    return dict(qp=g(0x300, 8, 6), ctu_ebit=g(0x358, 0, 20), frame_num=g(0x3bc, 16, 16), idr_pic_id=g(0x3c0, 0, 16),
                poc_lsb=g(0x3c0, 16, 16), dchs_txid=g(0x304, 0, 2), dchs_rxid=g(0x304, 2, 2), dchs_rxe=g(0x304, 5, 1))

def main():
    caps = {}
    for path in sys.argv[1:]:
        size = os.path.basename(path).split('.')[0]
        enc = next(ts for ts in parse(path).values() if len(ts[0]['w']) > 100)
        assert (enc[0]['w'][0x3b0] >> 2) & 31 == 5 and (enc[1]['w'][0x3b0] >> 2) & 31 == 1, size
        caps[size] = [(image(enc[k]['w']), inputs(enc[k]['w'])) for k in (0, 1)]
    full = caps['1280x720']
    out = ['// Generated by tools/vepu580_fixtures.py from tools/captures/*.log.gz; do not edit.',
           '//! Vendor MPP register images for the generated-register tests (see the generator).', '',
           'pub struct Inputs {', '    pub qp: u32,', '    pub ctu_ebit: u32,', '    pub frame_num: u32,',
           '    pub idr_pic_id: u32,', '    pub poc_lsb: u32,', '    pub dchs_txid: u32,', '    pub dchs_rxid: u32,',
           '    pub dchs_rxe: u32,', '}', '',
           'pub struct Capture {', '    pub width: u32,', '    pub height: u32,',
           '    /// (IDR, first P): the inputs, and (register byte offset, value) differing from the 1280x720 frame',
           '    pub frames: [(Inputs, &\'static [(u32, u32)]); 2],', '}', '']
    for k, name in ((0, 'IDR_1280X720'), (1, 'P_1280X720')):
        words = sorted(full[k][0].items())
        out.append('#[rustfmt::skip]')
        out.append(f'pub const {name}: [(u32, u32); {len(words)}] = [')
        for i in range(0, len(words), 6):
            out.append('    ' + ' '.join(f'({a:#06x}, {v:#010x}),' for a, v in words[i:i + 6]))
        out.append('];')
        out.append('')
    out.append('pub const CAPTURES: &[Capture] = &[')
    for size, frames in sorted(caps.items(), key=lambda kv: tuple(map(int, kv[0].split('x')))):
        w, h = size.split('x')
        out.append(f'    Capture {{ width: {w}, height: {h}, frames: [')
        for k in (0, 1):
            img, inp = frames[k]
            diff = sorted((a, v) for a, v in img.items() if v != full[k][0][a])
            fields = ', '.join(f'{n}: {v}' for n, v in inp.items())
            out.append(f'        (Inputs {{ {fields} }}, &[' + ' '.join(f'({a:#06x}, {v:#010x}),' for a, v in diff) + ']),')
        out.append('    ] },')
    out.append('];')
    print('\n'.join(out))

main()
