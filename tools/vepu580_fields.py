#!/usr/bin/env python3
"""Writes src/vepu580_regs.rs: every VEPU580 H.264 register field as (byte offset, lsb, width), from clang's record
layout of MPP's HalVepu580RegSet (mpp/hal/rkenc/h264e/hal_h264e_vepu580_reg.h + common/vepu580_common.h).

usage:
  MPP=~/src/mpp; printf '#include "hal_h264e_vepu580_reg.h"\\nHalVepu580RegSet x;\\n' > lay.c
  clang -fsyntax-only -Xclang -fdump-record-layouts-complete $(sed "s|\\$MPP|$MPP|" tools/mpp_includes.txt) lay.c > lay.txt
  tools/vepu580_fields.py lay.txt > src/vepu580_regs.rs
"""
import re, sys

BASES = {'reg_ctl': 0x0, 'reg_base': 0x280, 'reg_rc_klut': 0x1000, 'reg_s3': 0x1700, 'reg_rdo': 0x2000,
         'reg_scl': 0x2200, 'reg_osd': 0x3000, 'reg_st': 0x4000, 'reg_dbg': 0x5000}

def load(path):
    lines = open(path).read().split('\n')
    s = next(i for i, l in enumerate(lines) if l.rstrip().endswith('| struct HalVepu580Reg_t'))
    stack, member_off, fields, arrays = [], {}, [], []
    for l in lines[s + 1:]:
        if not l.strip() or 'sizeof=' in l:
            break
        m = re.match(r'\s*(\d+)(?::(\d+)-(\d+))?\s*\|(\s*)(.*)$', l)
        if not m:
            continue
        off, depth, decl = int(m[1]), (len(m[4]) - 1) // 2, m[5].strip()
        name = decl.split()[-1]
        stack = stack[:depth - 1] + [name]
        if depth == 1:
            member_off[name] = off
            continue
        top = stack[0]
        rel = off - member_off[top]
        path = stack[1:]
        if any(p.startswith('reserve') for p in path):
            continue
        if m[2] is not None:
            fields.append((path, BASES[top] + rel // 4 * 4, (rel % 4) * 8 + int(m[2]), int(m[3]) - int(m[2]) + 1, top))
        elif re.match(r'(RK_U32|RK_S32)\[(\d+)\]', decl):
            n = int(re.match(r'\w+\[(\d+)\]', decl)[1])
            arrays.append((path, BASES[top] + rel, n, top))
        elif decl.startswith(('RK_U32 ', 'RK_S32 ')):
            fields.append((path, BASES[top] + rel, 0, 32, top))
    return fields, arrays

def ident(path):
    return '_'.join(path).upper()

def main():
    fields, arrays = load(sys.argv[1])
    out = ['// Generated by tools/vepu580_fields.py from MPP\'s hal_h264e_vepu580_reg.h; do not edit.',
           '//! Every VEPU580 H.264 register field, one module per register class, named by its path in MPP\'s structs.',
           '#![allow(dead_code)]', '', 'use crate::vepu580::{f, Field};', '',
           '/// A run of whole registers.', '#[derive(Clone, Copy, Debug)]',
           'pub struct Array {', '    pub addr: u32,', '    pub len: u32,', '}', '']
    for top in BASES:
        fs = [x for x in fields if x[4] == top]
        ars = [x for x in arrays if x[3] == top]
        if not fs and not ars:
            continue
        out.append(f'pub mod {top} {{')
        out.append('    use super::*;')
        seen = set()
        for path, addr, lsb, width, _ in fs:
            n = ident(path)
            if n in seen:
                continue
            seen.add(n)
            out.append(f'    pub const {n}: Field = f({addr:#06x}, {lsb}, {width});')
        for path, addr, n, _ in ars:
            out.append(f'    pub const {ident(path)}: Array = Array {{ addr: {addr:#06x}, len: {n} }};')
        out.append('}')
        out.append('')
    print('\n'.join(out))

main()
