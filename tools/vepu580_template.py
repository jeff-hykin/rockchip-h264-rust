#!/usr/bin/env python3
"""Writes src/vepu580_template.rs: the VEPU580 register image the vendor MPP build programs for a 1280x720 H.264
CBR stream on AOS, taken from an mppshim.so capture (tools/mppshim.c) of
`gst-launch-1.0 ... mppjpegdec ! mpph264enc rc-mode=cbr bps=4000000 bps-max=5000000 gop=30 ...`.

Frame 0 (IDR) gives the full image; frame 1 (the first P) gives the P-frame overrides. Both are in the tuner's
initial (static scene) state. Registers that depend on the frame (buffers, QP, rate-control targets, slice
syntax, dual-core ids) keep the IDR's values here; src/vepu580.rs sets those fields every frame. Only the buffer
address registers (dmabuf fds of the capture run) are cleared.

usage: tools/vepu580_template.py tools/captures/ref_n420.log.gz > src/vepu580_template.rs
"""
import sys
from mpplog import parse

CLASSES = [('CTL', 0x0000, 0x005c), ('BASE', 0x0280, 0x03f4), ('RC', 0x1000, 0x10e0), ('S3', 0x1700, 0x19cc),
           ('RDO', 0x2000, 0x21e4), ('SCL', 0x2200, 0x2c98)]
# buffer address registers: dmabuf fds of the capture run
FDS = set(range(0x280, 0x2c0, 4))
# fields the encoder sets every frame: enc_pic (pic_qp), dual_core, rc_qp, rc_tgt, slice syntax, rc_dthd
PER_FRAME = FDS | {0x300, 0x304, 0x354, 0x358, 0x3b0, 0x3bc, 0x3c0} | set(range(0x1008, 0x102c, 4))

def main():
    tasks = parse(sys.argv[1])
    enc = next(ts for ts in tasks.values() if len(ts[0]['w']) > 100)
    i_frame, p_frame = enc[0]['w'], enc[1]['w']
    assert (i_frame[0x3b0] >> 2) & 31 == 5 and (p_frame[0x3b0] >> 2) & 31 == 1, 'frame 0 must be the IDR, frame 1 a P'
    out = ['// Generated by tools/vepu580_template.py from tools/captures/ref_n420.log.gz; do not edit.',
           '//! The vendor MPP build\'s VEPU580 register image for 1280x720 H.264 High CBR on AOS (see the generator).', '']
    for name, start, end in CLASSES:
        words = [0 if a in FDS else i_frame.get(a, 0) for a in range(start, end + 4, 4)]
        out.append(f'pub const {name}_OFFSET: u32 = {start:#06x};')
        out.append('#[rustfmt::skip]')
        out.append(f'pub const {name}: [u32; {len(words)}] = [')
        for k in range(0, len(words), 8):
            out.append('    ' + ' '.join(f'{w:#010x},' for w in words[k:k + 8]))
        out.append('];')
        out.append('')
    overrides = [(a, p_frame[a]) for a in sorted(p_frame) if a not in PER_FRAME and p_frame[a] != i_frame.get(a)]
    out.append('/// (register byte offset, value) where a P frame differs from the IDR image above.')
    out.append('#[rustfmt::skip]')
    out.append(f'pub const P_OVERRIDES: [(u32, u32); {len(overrides)}] = [')
    for a, v in overrides:
        out.append(f'    ({a:#06x}, {v:#010x}),')
    out.append('];')
    print('\n'.join(out))

main()
